from __future__ import annotations

"""Sprint 4 – Artifact Engine.

Generates the three flagship artifacts:
  - Decision_Note.docx    (python-docx)
  - Inspection_Data.xlsx   (openpyxl) — required columns per PRD §27
  - Evidence_Report.pdf    (fpdf2) — minimum path

Each artifact undergoes:
  - Structural validation: file opens without corruption
  - Semantic validation: required fields present
"""

import io
import logging
from typing import Any, Dict, List, Optional

from app.schemas.decision_package import (
    ArtifactManifest,
    ArtifactRecord,
    CalculationResult,
    VerificationReport,
)
from app.schemas.evidence import EvidenceObject

logger = logging.getLogger(__name__)


class ArtifactEngine:
    """Generates and validates the flagship artifact set."""

    # ------------------------------------------------------------------
    # DOCX — Decision Note
    # ------------------------------------------------------------------

    def create_docx(
        self,
        task_id: str,
        title: str,
        summary: str,
        evidence_objects: List[EvidenceObject],
        calculation_results: List[CalculationResult],
        verification_report: Optional[VerificationReport] = None,
    ) -> ArtifactRecord:
        """Generate Decision_Note.docx with evidence references and calculation results."""
        from docx import Document
        from docx.shared import Pt, Inches

        doc = Document()

        # Title
        heading = doc.add_heading(title, level=0)
        doc.add_paragraph(f"Task ID: {task_id}")
        doc.add_paragraph(f"Generated by SAFIRE Artifact Engine")
        doc.add_paragraph("")

        # Executive Summary
        doc.add_heading("Executive Summary", level=1)
        doc.add_paragraph(summary)

        # Evidence Summary
        doc.add_heading("Evidence References", level=1)
        for ev in evidence_objects:
            p = doc.add_paragraph(style="List Bullet")
            p.add_run(f"[{ev.evidence_id}] ").bold = True
            p.add_run(
                f"Type: {ev.evidence_type} | Page: {ev.page_number} | "
                f"Confidence: {ev.confidence:.2f}"
            )
            doc.add_paragraph(
                f"    {ev.extracted_text[:200]}...",
            ) if len(ev.extracted_text) > 200 else doc.add_paragraph(
                f"    {ev.extracted_text}",
            )

        # Calculation Results
        if calculation_results:
            doc.add_heading("Deterministic Calculation Results", level=1)
            table = doc.add_table(rows=1, cols=5)
            table.style = "Table Grid"
            headers = table.rows[0].cells
            headers[0].text = "Parameter"
            headers[1].text = "Result"
            headers[2].text = "Threshold"
            headers[3].text = "Status"
            headers[4].text = "Evidence Ref"

            for calc in calculation_results:
                row = table.add_row().cells
                row[0].text = calc.parameter_name
                row[1].text = f"{calc.primary_result:.4f}"
                row[2].text = f"{calc.threshold}" if calc.threshold else "N/A"
                row[3].text = calc.status
                row[4].text = calc.evidence_reference

        # Verification Summary
        if verification_report:
            doc.add_heading("Verification Summary", level=1)
            doc.add_paragraph(
                f"Overall Outcome: {verification_report.overall_outcome}"
            )
            for check in verification_report.checks:
                status_mark = "✓" if check.passed else "✗"
                doc.add_paragraph(
                    f"  {status_mark} {check.check_type}: {check.detail}"
                )

        # Save to bytes
        buffer = io.BytesIO()
        doc.save(buffer)
        content = buffer.getvalue()

        record = ArtifactRecord(
            task_id=task_id,
            filename="Decision_Note.docx",
            artifact_type="DOCX",
            file_size_bytes=len(content),
            content=content,
            evidence_references=[ev.evidence_id for ev in evidence_objects],
        )

        # Validate
        record.structural_valid = self._validate_docx_structural(content)
        record.semantic_valid = self._validate_docx_semantic(content, evidence_objects)

        logger.info("Created Decision_Note.docx (%d bytes)", len(content))
        return record

    # ------------------------------------------------------------------
    # XLSX — Inspection Data
    # ------------------------------------------------------------------

    def create_xlsx(
        self,
        task_id: str,
        calculation_results: List[CalculationResult],
        evidence_objects: List[EvidenceObject],
    ) -> ArtifactRecord:
        """Generate Inspection_Data.xlsx with required columns per PRD §27.

        Required columns: measurement, current_value, threshold, status, evidence_reference
        """
        from openpyxl import Workbook
        from openpyxl.styles import Font, PatternFill, Alignment, Border, Side

        wb = Workbook()
        ws = wb.active
        ws.title = "Inspection Data"

        # Header styling
        header_font = Font(bold=True, size=12, color="FFFFFF")
        header_fill = PatternFill(start_color="1F4E79", end_color="1F4E79", fill_type="solid")
        thin_border = Border(
            left=Side(style="thin"),
            right=Side(style="thin"),
            top=Side(style="thin"),
            bottom=Side(style="thin"),
        )

        # Required column headers per PRD §27
        headers = ["measurement", "current_value", "threshold", "status", "evidence_reference"]
        for col_idx, header in enumerate(headers, 1):
            cell = ws.cell(row=1, column=col_idx, value=header)
            cell.font = header_font
            cell.fill = header_fill
            cell.alignment = Alignment(horizontal="center")
            cell.border = thin_border

        # Data rows from calculation results
        for row_idx, calc in enumerate(calculation_results, 2):
            ws.cell(row=row_idx, column=1, value=calc.parameter_name).border = thin_border
            ws.cell(row=row_idx, column=2, value=calc.primary_result).border = thin_border
            ws.cell(row=row_idx, column=3, value=calc.threshold or "N/A").border = thin_border

            status_cell = ws.cell(row=row_idx, column=4, value=calc.status)
            status_cell.border = thin_border
            if calc.status == "PASS":
                status_cell.fill = PatternFill(start_color="C6EFCE", end_color="C6EFCE", fill_type="solid")
            else:
                status_cell.fill = PatternFill(start_color="FFC7CE", end_color="FFC7CE", fill_type="solid")

            ws.cell(row=row_idx, column=5, value=calc.evidence_reference).border = thin_border

        # Auto-size columns
        for col_idx in range(1, 6):
            ws.column_dimensions[chr(64 + col_idx)].width = 22

        # Save to bytes
        buffer = io.BytesIO()
        wb.save(buffer)
        content = buffer.getvalue()

        record = ArtifactRecord(
            task_id=task_id,
            filename="Inspection_Data.xlsx",
            artifact_type="XLSX",
            file_size_bytes=len(content),
            content=content,
            evidence_references=[calc.evidence_reference for calc in calculation_results],
        )

        # Validate
        record.structural_valid = self._validate_xlsx_structural(content)
        record.semantic_valid = self._validate_xlsx_semantic(content)

        logger.info("Created Inspection_Data.xlsx (%d bytes)", len(content))
        return record

    # ------------------------------------------------------------------
    # PDF — Evidence Report (minimum path)
    # ------------------------------------------------------------------

    def create_pdf(
        self,
        task_id: str,
        evidence_objects: List[EvidenceObject],
        calculation_results: Optional[List[CalculationResult]] = None,
        verification_report: Optional[VerificationReport] = None,
    ) -> ArtifactRecord:
        """Generate Evidence_Report.pdf — minimum path per PRD §27."""
        from fpdf import FPDF

        pdf = FPDF()
        pdf.set_auto_page_break(auto=True, margin=15)
        pdf.add_page()

        # Title
        pdf.set_font("Helvetica", "B", 18)
        pdf.cell(0, 12, "SAFIRE Evidence Report", new_x="LMARGIN", new_y="NEXT", align="C")
        pdf.set_font("Helvetica", "", 10)
        pdf.cell(0, 8, f"Task ID: {task_id}", new_x="LMARGIN", new_y="NEXT", align="C")
        pdf.ln(10)

        # Evidence Summary
        pdf.set_font("Helvetica", "B", 14)
        pdf.cell(0, 10, "Evidence Objects", new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", "", 9)

        for ev in evidence_objects:
            pdf.set_font("Helvetica", "B", 10)
            pdf.cell(0, 7, self._sanitize_for_pdf(f"[{ev.evidence_id}] {ev.evidence_type}"), new_x="LMARGIN", new_y="NEXT")
            pdf.set_font("Helvetica", "", 9)
            pdf.cell(0, 5, self._sanitize_for_pdf(f"Page: {ev.page_number} | Confidence: {ev.confidence:.2f} | Hash: {ev.source_hash[:16]}..."), new_x="LMARGIN", new_y="NEXT")
            # Truncate long text to fit
            text = ev.extracted_text[:300]
            pdf.multi_cell(0, 5, self._sanitize_for_pdf(f"  {text}"))
            pdf.ln(3)

        # Calculation Results
        if calculation_results:
            pdf.add_page()
            pdf.set_font("Helvetica", "B", 14)
            pdf.cell(0, 10, "Deterministic Calculation Results", new_x="LMARGIN", new_y="NEXT")
            pdf.set_font("Helvetica", "", 9)

            for calc in calculation_results:
                status_mark = "PASS" if calc.status == "PASS" else "FAIL"
                pdf.cell(
                    0, 6,
                    self._sanitize_for_pdf(
                        f"  {calc.parameter_name}: {calc.primary_result:.4f} "
                        f"(threshold: {calc.threshold}, status: {status_mark})"
                    ),
                    new_x="LMARGIN", new_y="NEXT",
                )

        # Verification Summary
        if verification_report:
            pdf.ln(8)
            pdf.set_font("Helvetica", "B", 14)
            pdf.cell(0, 10, "Verification Summary", new_x="LMARGIN", new_y="NEXT")
            pdf.set_font("Helvetica", "", 9)
            pdf.cell(0, 6, self._sanitize_for_pdf(f"Overall: {verification_report.overall_outcome}"), new_x="LMARGIN", new_y="NEXT")
            for check in verification_report.checks:
                mark = "PASS" if check.passed else "FAIL"
                pdf.cell(0, 5, self._sanitize_for_pdf(f"  [{mark}] {check.check_type}: {check.detail[:80]}"), new_x="LMARGIN", new_y="NEXT")

        # Save to bytes
        content = pdf.output()

        record = ArtifactRecord(
            task_id=task_id,
            filename="Evidence_Report.pdf",
            artifact_type="PDF",
            file_size_bytes=len(content),
            content=content,
            evidence_references=[ev.evidence_id for ev in evidence_objects],
        )

        record.structural_valid = self._validate_pdf_structural(content)
        record.semantic_valid = True  # Minimum path — content presence is sufficient

        logger.info("Created Evidence_Report.pdf (%d bytes)", len(content))
        return record

    # ------------------------------------------------------------------
    # Generate full manifest
    # ------------------------------------------------------------------

    def generate_full_manifest(
        self,
        task_id: str,
        title: str,
        summary: str,
        evidence_objects: List[EvidenceObject],
        calculation_results: List[CalculationResult],
        verification_report: Optional[VerificationReport] = None,
    ) -> ArtifactManifest:
        """Generate all three flagship artifacts and return a manifest."""
        docx = self.create_docx(
            task_id, title, summary, evidence_objects,
            calculation_results, verification_report,
        )
        xlsx = self.create_xlsx(task_id, calculation_results, evidence_objects)
        pdf = self.create_pdf(
            task_id, evidence_objects, calculation_results, verification_report,
        )

        artifacts = [docx, xlsx, pdf]
        all_valid = all(a.structural_valid and a.semantic_valid for a in artifacts)

        manifest = ArtifactManifest(
            task_id=task_id,
            artifacts=artifacts,
            all_valid=all_valid,
        )

        logger.info(
            "Artifact manifest for task %s: %d artifacts, all_valid=%s",
            task_id, len(artifacts), all_valid,
        )
        return manifest

    # ------------------------------------------------------------------
    # Structural validation
    # ------------------------------------------------------------------

    @staticmethod
    def _validate_docx_structural(content: bytes) -> bool:
        """Validate DOCX opens without corruption."""
        try:
            from docx import Document
            doc = Document(io.BytesIO(content))
            return len(doc.paragraphs) > 0
        except Exception as exc:
            logger.warning("DOCX structural validation failed: %s", exc)
            return False

    @staticmethod
    def _validate_xlsx_structural(content: bytes) -> bool:
        """Validate XLSX opens without corruption."""
        try:
            from openpyxl import load_workbook
            wb = load_workbook(io.BytesIO(content))
            ws = wb.active
            return ws.max_row is not None and ws.max_row >= 1
        except Exception as exc:
            logger.warning("XLSX structural validation failed: %s", exc)
            return False

    @staticmethod
    def _validate_pdf_structural(content: bytes) -> bool:
        """Validate PDF is well-formed (starts with %PDF header)."""
        try:
            return content[:5] == b"%PDF-"
        except Exception as exc:
            logger.warning("PDF structural validation failed: %s", exc)
            return False

    # ------------------------------------------------------------------
    # Semantic validation
    # ------------------------------------------------------------------

    @staticmethod
    def _validate_docx_semantic(
        content: bytes, evidence_objects: List[EvidenceObject]
    ) -> bool:
        """Validate DOCX contains expected content."""
        try:
            from docx import Document
            doc = Document(io.BytesIO(content))
            full_text = "\n".join(p.text for p in doc.paragraphs)
            # Check at least one evidence ID appears
            has_evidence_ref = any(
                ev.evidence_id in full_text for ev in evidence_objects
            )
            has_title = len(doc.paragraphs) > 0 and len(doc.paragraphs[0].text) > 0
            return has_evidence_ref and has_title
        except Exception:
            return False

    @staticmethod
    def _sanitize_for_pdf(text: str) -> str:
        """Replace non-latin-1 characters with ASCII equivalents for Helvetica."""
        replacements = {
            "\u2014": "--",   # em-dash
            "\u2013": "-",    # en-dash
            "\u2018": "'",    # left single quote
            "\u2019": "'",    # right single quote
            "\u201c": '"',    # left double quote
            "\u201d": '"',    # right double quote
            "\u2026": "...",  # ellipsis
            "\u00b0": "deg",  # degree symbol
            "\u2022": "*",    # bullet
            "\u2713": "Y",    # check mark
            "\u2717": "X",    # cross mark
            "\u2192": "->",   # right arrow
            "\u2190": "<-",   # left arrow
        }
        for char, replacement in replacements.items():
            text = text.replace(char, replacement)
        # Final fallback: encode to latin-1, replacing unknown chars
        return text.encode("latin-1", errors="replace").decode("latin-1")

    @staticmethod
    def _validate_xlsx_semantic(content: bytes) -> bool:
        """Validate XLSX has the required columns per PRD §27."""
        try:
            from openpyxl import load_workbook
            wb = load_workbook(io.BytesIO(content))
            ws = wb.active

            required_columns = {
                "measurement", "current_value", "threshold",
                "status", "evidence_reference",
            }
            header_row = [
                str(cell.value).strip().lower()
                for cell in ws[1]
                if cell.value is not None
            ]
            return required_columns.issubset(set(header_row))
        except Exception:
            return False
